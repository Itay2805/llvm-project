#ifndef LLVM_LIB_TARGET_ARC4_INSTPRINTER_ARC4INSTPRINTER_H
#define LLVM_LIB_TARGET_ARC4_INSTPRINTER_ARC4INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class ARC4InstPrinter : public MCInstPrinter {
public:
  ARC4InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printOperand(const MCInst *MI, uint64_t /*Address*/, unsigned OpNum,
                    raw_ostream &O) {
    printOperand(MI, OpNum, O);
  }
  void printImm(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printBranchTarget(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printDelaySlot(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printCondCode(const MCInst *MI, unsigned OpNum, raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_ARC4_INSTPRINTER_ARC4INSTPRINTER_H
